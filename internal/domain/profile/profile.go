// Package profile models the Mihomo configurations the user imports:
// local files, remote subscriptions and Sub-Store outputs, with the
// metadata Kumo keeps about each.
package profile

import (
	"crypto/rand"
	"encoding/hex"
	"fmt"
	"net/url"
	"strconv"
	"strings"
	"time"
	"unicode"
)

// DefaultID is the generated profile that routes everything directly. It
// exists whether or not the user imported anything.
const DefaultID = "default"

// DefaultYAML is the direct profile Kumo runs with nothing imported.
const DefaultYAML = `proxies: []
proxy-groups:
  - name: Proxy
    type: select
    proxies:
      - DIRECT
rules:
  - MATCH,DIRECT
`

// Kind is where a profile's YAML comes from.
type Kind string

const (
	KindLocal  Kind = "local"
	KindRemote Kind = "remote"
	KindInline Kind = "inline"
)

// Usage is the traffic a subscription reports in its
// subscription-userinfo header.
type Usage struct {
	Upload   int64 `json:"upload"`
	Download int64 `json:"download"`
	Total    int64 `json:"total"`
	Expire   int64 `json:"expire,omitempty"`
}

// Used is upload plus download.
func (u Usage) Used() int64 { return u.Upload + u.Download }

// ParseUsage reads a subscription-userinfo header such as
// "upload=1; download=2; total=3; expire=4".
func ParseUsage(header string) (Usage, bool) {
	fields := map[string]int64{}
	for part := range strings.SplitSeq(header, ";") {
		key, value, ok := strings.Cut(part, "=")
		if !ok {
			continue
		}
		n, err := strconv.ParseFloat(strings.TrimSpace(value), 64)
		if err != nil {
			continue
		}
		fields[strings.ToLower(strings.TrimSpace(key))] = int64(n)
	}
	if len(fields) == 0 {
		return Usage{}, false
	}
	return Usage{Upload: fields["upload"], Download: fields["download"], Total: fields["total"], Expire: fields["expire"]}, true
}

// Profile is one configuration and what Kumo knows about it.
type Profile struct {
	ID        string     `json:"id"`
	Name      string     `json:"name"`
	Kind      Kind       `json:"kind"`
	RemoteURL string     `json:"remoteURL,omitempty"`
	HomeURL   string     `json:"homeURL,omitempty"`
	UpdatedAt *time.Time `json:"updatedAt,omitempty"`
	// AutoUpdate refreshes a remote profile on its interval.
	AutoUpdate bool `json:"autoUpdate"`
	// UseProxy fetches a remote profile through the running core.
	UseProxy bool `json:"useProxy"`
	// UpdateIntervalSeconds comes from the profile-update-interval header.
	UpdateIntervalSeconds int    `json:"updateIntervalSeconds,omitempty"`
	Usage                 *Usage `json:"subscriptionUserInfo,omitempty"`
	// SubStorePath is set for profiles generated by Sub-Store, such as
	// "/download/collection/work".
	SubStoreManaged bool   `json:"isSubStoreManaged,omitempty"`
	SubStorePath    string `json:"subStorePath,omitempty"`
}

// Summary is a profile as lists show it.
type Summary struct {
	Profile
	Current bool   `json:"isCurrent"`
	Source  string `json:"sourceDescription"`
}

// Default is the metadata of the generated direct profile.
func Default() Profile {
	return Profile{ID: DefaultID, Name: "Default", Kind: KindInline, AutoUpdate: true}
}

// SourceDescription says where the profile comes from in a few words.
func (p Profile) SourceDescription() string {
	switch p.Kind {
	case KindRemote:
		if u, err := url.Parse(p.RemoteURL); err == nil && u.Host != "" {
			return u.Host
		}
		return "Remote"
	case KindInline:
		return "Generated direct profile"
	default:
		return "Local YAML"
	}
}

// Summarize pairs the profile with whether it is the current one.
func (p Profile) Summarize(currentID string) Summary {
	return Summary{Profile: p, Current: p.ID == currentID, Source: p.SourceDescription()}
}

// IsDue reports whether an auto-updating remote profile should refresh.
func (p Profile) IsDue(now time.Time) bool {
	if p.Kind != KindRemote || !p.AutoUpdate || p.UpdateIntervalSeconds <= 0 {
		return false
	}
	if p.UpdatedAt == nil {
		return true
	}
	return now.Sub(*p.UpdatedAt) >= time.Duration(p.UpdateIntervalSeconds)*time.Second
}

// NewID derives a readable, unique ID from a name, such as "work-1a2b3c4d".
func NewID(name string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(name) {
		if r < unicode.MaxASCII && (unicode.IsLetter(r) || unicode.IsDigit(r) || r == '-' || r == '_') {
			b.WriteRune(r)
		} else {
			b.WriteRune('-')
		}
	}
	slug := strings.Trim(b.String(), "-")
	for strings.Contains(slug, "--") {
		slug = strings.ReplaceAll(slug, "--", "-")
	}
	suffix := make([]byte, 4)
	_, _ = rand.Read(suffix)
	if slug == "" {
		slug = "profile"
	}
	return slug + "-" + hex.EncodeToString(suffix)
}

// ValidateID rejects IDs that would escape the profiles directory.
func ValidateID(id string) error {
	if id == "" || strings.ContainsAny(id, `/\`) || strings.HasPrefix(id, ".") {
		return fmt.Errorf("invalid profile id %q", id)
	}
	return nil
}

// Document is a fetched remote profile and the headers it came with.
type Document struct {
	YAML                  string
	Name                  string
	HomeURL               string
	UpdateIntervalSeconds int
	Usage                 *Usage
}

// Repository keeps profiles and which one is current.
type Repository interface {
	// List returns every profile; the default one is always included.
	List() ([]Profile, error)
	Get(id string) (Profile, error)
	// Content is the profile's YAML.
	Content(id string) (string, error)
	// Save writes the profile's metadata and, when yaml is not nil, its YAML.
	Save(p Profile, yaml *string) error
	Delete(id string) error
	CurrentID() (string, error)
	SetCurrent(id string) error
}

// Fetcher downloads a remote profile, through the local proxy when
// proxyPort is set.
type Fetcher interface {
	Fetch(url string, proxyPort int) (Document, error)
}
